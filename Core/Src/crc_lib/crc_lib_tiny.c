// Reverses (reflects) bits in a 32-bit word.
static uint32_t reverse(uint32_t x) 
{
   x = ((x & 0x55555555) <<  1) | ((x >>  1) & 0x55555555);
   x = ((x & 0x33333333) <<  2) | ((x >>  2) & 0x33333333);
   x = ((x & 0x0F0F0F0F) <<  4) | ((x >>  4) & 0x0F0F0F0F);
   x = (x << 24) | ((x & 0xFF00) << 8) | ((x >> 8) & 0xFF00) | (x >> 24);
   return x;
}

void crc32_slow_init(uint32_t* crc)
{
  *crc = 0xFFFFFFFF;
}

void crc32_slow_update(uint32_t* crc, const uint8_t* buff, uint32_t len)
{
   for(uint32_t i=0; i<len; i++)
   {
      uint32_t byte = buff[i];         // Get next byte.
      byte = reverse(byte);            // 32-bit reversal.
      for (uint8_t j = 0; j <= 7; j++) // Do eight times.
      {    
         if ((int32_t)(*crc ^ byte) < 0) *crc = (*crc << 1) ^ 0x04C11DB7;
         else                            *crc = (*crc << 1);
         byte = byte << 1;            // Ready next msg bit.
      }
   }
}

void crc32_slow_finish(uint32_t* crc)
{
  *crc=reverse(~(*crc));
}

uint32_t crc32_slow_full(const uint8_t* buff, uint32_t len)
{
  uint32_t crc;
  crc32_slow_init(&crc);
  crc32_slow_update(&crc, buff, len);
  crc32_slow_finish(&crc);
  return crc;
}

