uint16_t crc16_slow(const uint8_t *pcBlock, uint16_t len)
{
  uint16_t crc = 0xFFFF;
  uint8_t i;
  
  while (len--)
  {
    crc ^= *pcBlock++ << 8;
    
    for (i = 0; i < 8; i++)
      crc = crc & 0x8000 ? (crc << 1) ^ 0x1021 : crc << 1;
  }
  
  return crc;
}

void crc16_slow_init(uint16_t* crc)
{
  *crc = 0xFFFF;
}

void crc16_slow_calc(uint16_t* crc, const uint8_t* buff, uint16_t len)
{
  uint8_t i;
  
  while(len--)
  {
    *crc ^= *buff++ << 8;
    
    for (i = 0; i < 8; i++)
      *crc = *crc & 0x8000 ? (*crc << 1) ^ 0x1021 : *crc << 1;
  }
}

void crc16_slow_finish(uint16_t* crc)
{
  (void)crc;
}

uint16_t crc16_slow_full(const uint8_t* buff, uint16_t len)
{
  uint16_t crc;
  crc16_slow_init(&crc);
  crc16_slow_calc(&crc, buff, len);
  crc16_slow_finish(&crc);
  return crc;
}

/*
Name  : CRC-16 
Poly  : x^16 + x^15 + x^2 + 1
*/
uint16_t crc16_modbus(const uint8_t *p, uint16_t len)
{
    uint8_t crc_hi;
    uint8_t crc_lo;
    uint8_t n;

    if (len>256U)
    {
        return (0);
    }

    n = (uint8_t)len;

    crc_hi = 0xFF;   // high byte of CRC initialized
    crc_lo = 0xFF;   // low byte of CRC initialized

    do
    {
        uint8_t i = crc_hi ^ *p++;        // will index into CRC lookup table
        crc_hi = crc_lo ^ (uint8_t)(auchCRCHi[i]);    // calculate the CRC
        crc_lo =          (uint8_t)(auchCRCLo[i]);
    }
    while (--n);         // pass through message buffer (max 256 items)

    return ((crc_hi << 8) | crc_lo);
}

